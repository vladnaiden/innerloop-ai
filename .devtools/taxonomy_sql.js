/**
 * Emit the taxonomy backfill as pure SQL.
 *
 * The database host runs Postgres and nothing else, and the classifier is regex-based so it cannot be
 * expressed as SQL directly. So evaluate it here over every DISTINCT vertical the registry holds and
 * ship the result as a literal map table — 1,143 rows, which Postgres joins against 186k in seconds.
 *
 *   node taxonomy_sql.js verticals.txt > taxonomy_backfill.sql
 *
 * Re-running it is a no-op on clean data. The UPDATEs are guarded so a row is only written when the
 * value actually changes, which keeps the write set small and the run resumable.
 */
const fs = require("fs");
const { classify } = require("./taxonomy.js");

const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const src = process.argv[2];
const values = [...new Set(
  fs.readFileSync(src, "utf8").trim().split("\n")
    .map(l => l.slice(0, l.lastIndexOf("|")))
    .filter(v => v && v.trim()),
)];

const rows = values.map(v => {
  const c = classify(v);
  return `(${q(v)}, ${q(c.category)}, ${c.sub ? q(c.sub) : "NULL"})`;
});

console.log(`-- generated by taxonomy_sql.js from taxonomy.js — do not hand-edit
-- ${values.length} distinct source verticals -> 22 categories
BEGIN;

ALTER TABLE mr_program ADD COLUMN IF NOT EXISTS vertical_original text;
ALTER TABLE mr_program ADD COLUMN IF NOT EXISTS subvertical_en   text;

-- the verbatim copy of what the source published, kept whatever happens to \`vertical\` later
UPDATE mr_program SET vertical_original = btrim(vertical)
 WHERE vertical IS NOT NULL AND btrim(vertical) <> '' AND vertical_original IS DISTINCT FROM btrim(vertical);

CREATE TEMP TABLE tax_map (raw text PRIMARY KEY, category text NOT NULL, sub text) ON COMMIT DROP;
INSERT INTO tax_map (raw, category, sub) VALUES
${rows.join(",\n")}
ON CONFLICT (raw) DO NOTHING;

ANALYZE tax_map;

UPDATE mr_program p SET vertical_en = m.category, subvertical_en = m.sub
  FROM tax_map m
 WHERE btrim(p.vertical) = m.raw
   AND (p.vertical_en IS DISTINCT FROM m.category OR p.subvertical_en IS DISTINCT FROM m.sub);

-- a row with no vertical at all is Other, not NULL: the filter must be able to offer every program
UPDATE mr_program SET vertical_en = 'Other'
 WHERE (vertical IS NULL OR btrim(vertical) = '') AND vertical_en IS DISTINCT FROM 'Other';

CREATE INDEX IF NOT EXISTS ix_mr_subvertical_en ON mr_program (lower(btrim(subvertical_en)));

COMMIT;

\\echo '--- result ---'
SELECT vertical_en, count(*)::int rows, count(DISTINCT subvertical_en)::int subs
  FROM mr_program GROUP BY 1 ORDER BY 2 DESC;`);
