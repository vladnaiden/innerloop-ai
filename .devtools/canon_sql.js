#!/usr/bin/env node
/**
 * Emits the canonical backfill as pure SQL, generated from canon.js so there is still one dictionary.
 * The database host runs Postgres and nothing else — no Node, no npm — so the backfill has to be a file
 * psql can read.  node canon_sql.js > canon_backfill.sql
 */
const { VERTICAL, FREQUENCY, METHOD, RATE_TYPE } = require("./canon.js");
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const rows = [];
for (const [kind, dict] of [["vertical", VERTICAL], ["frequency", FREQUENCY], ["method", METHOD], ["rate_type", RATE_TYPE]])
  for (const [canon, raws] of Object.entries(dict))
    for (const raw of raws) rows.push(`(${q(kind)},${q(raw)},${q(canon)})`);

console.log(`-- Generated by canon_sql.js from canon.js — do not edit by hand.
-- Writes the canonical *_en columns from the raw ones. Raw values are never modified.
SET statement_timeout = 0;
CREATE TEMP TABLE canon_map(kind text, raw text, canon text);
INSERT INTO canon_map(kind, raw, canon) VALUES
${rows.join(",\n")};
CREATE INDEX ON canon_map(kind, raw);
ANALYZE canon_map;

-- 1. vertical: mapped values, then anything unmapped keeps its own label
UPDATE mr_program p SET vertical_en = m.canon
  FROM canon_map m WHERE m.kind='vertical' AND lower(btrim(p.vertical)) = m.raw
  AND p.vertical_en IS DISTINCT FROM m.canon;
UPDATE mr_program SET vertical_en = btrim(vertical)
  WHERE vertical IS NOT NULL AND btrim(vertical) <> '' AND vertical_en IS NULL;

-- 2. rate type
UPDATE mr_program p SET rate_type_en = m.canon
  FROM canon_map m WHERE m.kind='rate_type' AND lower(btrim(p.rate_type)) = m.raw
  AND p.rate_type_en IS DISTINCT FROM m.canon;
UPDATE mr_program SET rate_type_en = btrim(rate_type)
  WHERE rate_type IS NOT NULL AND btrim(rate_type) <> '' AND rate_type_en IS NULL;

-- 3. payment methods: canonicalise each element of the array, drop duplicates, keep unmapped ones as-is
UPDATE mr_program p SET payment_methods_en = s.arr
  FROM (
    SELECT p2.seq, array_agg(DISTINCT COALESCE(m.canon, btrim(x))) AS arr
    FROM mr_program p2, unnest(p2.payment_methods) x
    LEFT JOIN canon_map m ON m.kind='method' AND m.raw = lower(btrim(x))
    WHERE btrim(x) <> ''
    GROUP BY p2.seq
  ) s
  WHERE p.seq = s.seq AND p.payment_methods_en IS DISTINCT FROM s.arr;

-- 4. payment frequency: one value, or several separated by , ; / — canonicalise each part
UPDATE mr_program p SET payment_frequency_en = s.txt
  FROM (
    SELECT p2.seq, string_agg(DISTINCT COALESCE(m.canon, btrim(part)), ', ') AS txt
    FROM mr_program p2,
         unnest(regexp_split_to_array(p2.payment_frequency, '\\s*[,;/|]\\s*| and | или ')) part
    LEFT JOIN canon_map m ON m.kind='frequency' AND m.raw = lower(btrim(part))
    WHERE p2.payment_frequency IS NOT NULL AND btrim(part) <> ''
    GROUP BY p2.seq
  ) s
  WHERE p.seq = s.seq AND p.payment_frequency_en IS DISTINCT FROM s.txt;

ANALYZE mr_program;
SELECT 'vertical_en' AS col, count(*) FILTER (WHERE vertical_en IS NOT NULL) AS filled,
       count(DISTINCT vertical_en) AS distinct_values FROM mr_program
UNION ALL SELECT 'rate_type_en', count(*) FILTER (WHERE rate_type_en IS NOT NULL), count(DISTINCT rate_type_en) FROM mr_program
UNION ALL SELECT 'payment_frequency_en', count(*) FILTER (WHERE payment_frequency_en IS NOT NULL), count(DISTINCT payment_frequency_en) FROM mr_program
UNION ALL SELECT 'payment_methods_en', count(*) FILTER (WHERE payment_methods_en IS NOT NULL), 0 FROM mr_program;`);
