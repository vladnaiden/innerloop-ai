#!/usr/bin/env bash
# SemVer release from Conventional Commits. Dry run unless --go.
#
#   bash scripts/release.sh          # show the next version and its changelog section
#   bash scripts/release.sh --go     # prepend it to CHANGELOG.md, commit ONLY that file, annotated tag
#
# Bump since the last vX.Y.Z tag: breaking ("type!:" or a "BREAKING CHANGE:" footer) → major,
# feat → minor, anything else → patch. While the major is 0 (pre-1.0, SemVer §4) a breaking
# change bumps the minor instead. Tags stay local — pushing is the owner's call:
#   git push origin main --follow-tags
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

GO=0; [ "${1:-}" = "--go" ] && GO=1

last=$(git describe --tags --abbrev=0 --match 'v[0-9]*.[0-9]*.[0-9]*' 2>/dev/null || true)
[ -n "$last" ] || { echo "No vX.Y.Z tag yet — create the baseline first: git tag -a v0.1.0 <sha> -m …" >&2; exit 1; }
range="$last..HEAD"

python3 -I - "$last" "$range" "$GO" <<'PY'
import re, subprocess, sys, datetime
last, rng, go = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
raw = subprocess.run(["git", "log", "--no-merges", "--format=%h%x1f%s%x1f%b%x1e", rng],
                     capture_output=True, text=True, check=True).stdout
hdr = re.compile(r"^(?P<type>[a-z]+)(?:\((?P<scope>[^()]+)\))?(?P<bang>!)?: (?P<desc>.+)$")
groups = {"Breaking": [], "Features": [], "Fixes": [], "Performance": [], "Other": []}
bump = 0  # 0 patch, 1 minor, 2 major
n = 0
for rec in filter(None, (r.strip("\n") for r in raw.split("\x1e"))):
    sha, subj, body = (rec.split("\x1f") + ["", ""])[:3]
    m = hdr.match(subj)
    if m and m["type"] == "chore" and (m["scope"] or "") == "release":
        continue
    n += 1
    breaking = bool(m and m["bang"]) or bool(re.search(r"^BREAKING[ -]CHANGE:", body, re.M))
    line = (f"**{m['scope']}:** {m['desc']}" if m and m["scope"] else (m["desc"] if m else subj)) + f" ({sha})"
    if breaking:
        groups["Breaking"].append(line); bump = 2
    elif m and m["type"] == "feat":
        groups["Features"].append(line); bump = max(bump, 1)
    elif m and m["type"] == "fix":
        groups["Fixes"].append(line)
    elif m and m["type"] == "perf":
        groups["Performance"].append(line)
    else:
        groups["Other"].append(line)
if n == 0:
    print(f"Nothing to release: no commits since {last}."); sys.exit(0)
major, minor, patch = map(int, last.lstrip("v").split("."))
if bump == 2 and major == 0: bump = 1
nxt = {2: (major + 1, 0, 0), 1: (major, minor + 1, 0), 0: (major, minor, patch + 1)}[bump]
ver = "v%d.%d.%d" % nxt
section = [f"## {ver} — {datetime.date.today():%d.%m.%Y}", ""]
for g, items in groups.items():
    if items:
        section += [f"### {g}", ""] + [f"- {i}" for i in items] + [""]
text = "\n".join(section)
print(f"{last} → {ver}  ({n} commits, bump: {['patch','minor','major'][bump]})\n\n{text}")
if not go:
    print("Dry run. Apply with: bash scripts/release.sh --go"); sys.exit(0)

# --go: CHANGELOG.md must not carry someone else's uncommitted edits.
if subprocess.run(["git", "diff", "--quiet", "HEAD", "--", "CHANGELOG.md"]).returncode != 0:
    sys.exit("CHANGELOG.md has uncommitted changes — commit or restore them first.")
head = "# Changelog\n\nVersions follow [SemVer](https://semver.org); commits follow [Conventional Commits](https://www.conventionalcommits.org). Generated by `scripts/release.sh`.\n\n"
try:
    old = open("CHANGELOG.md", encoding="utf-8").read()
    i = old.find("\n## ")          # keep every earlier release section, drop the old header
    old = old[i + 1:] if i >= 0 else ""
except FileNotFoundError:
    old = ""
open("CHANGELOG.md", "w", encoding="utf-8").write(head + text + "\n" + old)
subprocess.run(["git", "add", "CHANGELOG.md"], check=True)
subprocess.run(["git", "commit", "--only", "CHANGELOG.md", "-m", f"chore(release): {ver}"], check=True)
subprocess.run(["git", "tag", "-a", ver, "-m", f"Release {ver}\n\n{text}"], check=True)
print(f"Tagged {ver}. Not pushed — on his word: git push origin main --follow-tags")
PY
